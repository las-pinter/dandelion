//! The TOML allowlist and the sudoers drop-in generated from it.
//!
//! The allowlist file is the policy; the drop-in is the second, independent
//! gate that lets `sudo -n systemctl` run the listed verbs. Both reject a unit
//! containing a backslash, because sudoers reads it as an escape.

use std::path::{Path, PathBuf};

use dandelion_system::systemd::SudoAllowlist;

/// Why the allowlist file could not be used.
#[derive(Debug, thiserror::Error)]
pub enum AllowlistFileError {
    /// The file exists but could not be read.
    #[error("cannot read the allowlist {path}: {source}")]
    Read {
        /// The allowlist path.
        path: PathBuf,
        /// The filesystem error.
        #[source]
        source: std::io::Error,
    },
    /// The file is not valid TOML for the allowlist schema.
    #[error("cannot parse the allowlist {path}: {source}")]
    Parse {
        /// The allowlist path.
        path: PathBuf,
        /// The parser's error.
        #[source]
        source: toml::de::Error,
    },
    /// A listed unit contains a character sudoers would misread.
    #[error("the allowlist {path} lists unit `{unit}`, whose backslash sudoers reads as an escape")]
    UnsafeUnit {
        /// The allowlist path.
        path: PathBuf,
        /// The rejected unit.
        unit: String,
    },
}

/// Loads the allowlist from TOML; a missing file is an empty allowlist.
pub fn load_allowlist(path: &Path) -> Result<SudoAllowlist, AllowlistFileError> {
    let allowlist = match std::fs::read_to_string(path) {
        Ok(text) => toml::from_str(&text).map_err(|source| AllowlistFileError::Parse {
            path: path.to_path_buf(),
            source,
        })?,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => SudoAllowlist::new(),
        Err(source) => {
            return Err(AllowlistFileError::Read {
                path: path.to_path_buf(),
                source,
            });
        }
    };
    if let Some(rule) = allowlist
        .rules()
        .iter()
        .find(|rule| rule.unit.contains('\\'))
    {
        return Err(AllowlistFileError::UnsafeUnit {
            path: path.to_path_buf(),
            unit: rule.unit.clone(),
        });
    }
    Ok(allowlist)
}

/// Why the sudoers drop-in could not be generated.
#[derive(Debug, thiserror::Error)]
pub enum DropInError {
    /// A backslash is a sudoers escape, so the line would not mean what it says.
    #[error("unit `{unit}` contains a backslash, which sudoers reads as an escape")]
    UnsafeUnit {
        /// The rejected unit.
        unit: String,
    },
    /// The account name is not a plain name, or is the sudoers keyword `ALL`.
    #[error("`{user}` is not a plain account name; pass --user")]
    UnsafeUser {
        /// The rejected account name.
        user: String,
    },
}

/// Renders the sudoers drop-in that matches one allowlist.
///
/// One line per rule, one command per verb, all without a password. A unit
/// with a backslash is refused rather than escaped by guesswork, and `ALL` is
/// refused as an account because it would grant every local user.
pub fn sudoers_drop_in(allowlist: &SudoAllowlist, user: &str) -> Result<String, DropInError> {
    if user.is_empty()
        || user.eq_ignore_ascii_case("ALL")
        || !user.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.')
        })
    {
        return Err(DropInError::UnsafeUser {
            user: user.to_owned(),
        });
    }
    let mut lines = vec![
        "# Generated by `dandelion sudoers` from sudo-allowlist.toml; do not edit.".to_owned(),
        "# Install with `just install-sudoers`.".to_owned(),
    ];
    for rule in allowlist.rules() {
        if rule.unit.contains('\\') {
            return Err(DropInError::UnsafeUnit {
                unit: rule.unit.clone(),
            });
        }
        if rule.verbs.is_empty() {
            continue;
        }
        let commands: Vec<String> = rule
            .verbs
            .iter()
            .map(|action| {
                format!(
                    "/usr/bin/systemctl {} {}",
                    action.systemctl_verb(),
                    rule.unit
                )
            })
            .collect();
        lines.push(format!(
            "{user} ALL=(root) NOPASSWD: {}",
            commands.join(", ")
        ));
    }
    lines.push(String::new());
    Ok(lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use std::fs;

    use dandelion_system::systemd::{SudoAllowlist, UnitAction};
    use tempfile::TempDir;

    use super::{AllowlistFileError, DropInError, load_allowlist, sudoers_drop_in};

    fn allowlist_text() -> &'static str {
        r#"
[[rules]]
unit = "nginx.service"
verbs = ["restart", "start"]

[[rules]]
unit = "docker.service"
verbs = ["restart"]
"#
    }

    fn write(dir: &TempDir, text: &str) -> std::path::PathBuf {
        let path = dir.path().join("sudo-allowlist.toml");
        fs::write(&path, text).expect("write fixture");
        path
    }

    #[test]
    fn a_missing_file_is_an_empty_allowlist() {
        let dir = TempDir::new().expect("temp dir");
        let allowlist =
            load_allowlist(&dir.path().join("sudo-allowlist.toml")).expect("missing file");

        assert!(allowlist.is_empty());
    }

    #[test]
    fn a_valid_file_loads_every_rule() {
        let dir = TempDir::new().expect("temp dir");
        let allowlist = load_allowlist(&write(&dir, allowlist_text())).expect("valid allowlist");

        assert_eq!(allowlist.rules().len(), 2);
        assert!(allowlist.check("nginx.service", UnitAction::Start).is_ok());
        assert!(allowlist.check("docker.service", UnitAction::Stop).is_err());
    }

    #[test]
    fn a_malformed_file_is_a_parse_error() {
        let dir = TempDir::new().expect("temp dir");
        let path = write(&dir, "[[rules]]\nunit = \"../evil\"\nverbs = [\"start\"]\n");

        let error = load_allowlist(&path).expect_err("invalid unit is refused");

        assert!(matches!(error, AllowlistFileError::Parse { .. }));
    }

    #[test]
    fn a_backslash_unit_is_refused_at_load() {
        let dir = TempDir::new().expect("temp dir");
        let path = write(
            &dir,
            "[[rules]]\nunit = \"odd\\\\unit.service\"\nverbs = [\"restart\"]\n",
        );

        let error = load_allowlist(&path).expect_err("backslash is refused");

        assert!(matches!(error, AllowlistFileError::UnsafeUnit { .. }));
    }

    #[test]
    fn the_drop_in_names_every_command_per_rule() {
        let dir = TempDir::new().expect("temp dir");
        let allowlist = load_allowlist(&write(&dir, allowlist_text())).expect("valid allowlist");

        let text = sudoers_drop_in(&allowlist, "dev").expect("drop-in");

        assert!(text.contains(
            "dev ALL=(root) NOPASSWD: /usr/bin/systemctl restart nginx.service, /usr/bin/systemctl start nginx.service"
        ));
        assert!(
            text.contains("dev ALL=(root) NOPASSWD: /usr/bin/systemctl restart docker.service")
        );
    }

    #[test]
    fn an_unsafe_unit_or_user_is_refused() {
        let mut allowlist = SudoAllowlist::new();
        allowlist
            .allow(r"odd\unit.service", vec![UnitAction::Restart])
            .expect("the crate permits the name");
        assert!(matches!(
            sudoers_drop_in(&allowlist, "dev"),
            Err(DropInError::UnsafeUnit { .. })
        ));

        let empty = SudoAllowlist::new();
        for user in ["", "dev, ALL", "ALL", "all", r"dev\"] {
            assert!(
                matches!(
                    sudoers_drop_in(&empty, user),
                    Err(DropInError::UnsafeUser { .. })
                ),
                "{user}"
            );
        }
    }
}
